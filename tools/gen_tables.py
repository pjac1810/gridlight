"""Generate src/tables.h for GRVBOX (integers only on the FM-1).

SVF_G[i]    tan(pi fc / fs) in Q16 for the state-variable filters; fc 20 Hz .. 16 kHz, exponential (i 0..1023)
ENV_MS[v]   a time for a 0..127 value: 1 ms .. 8 s, exponential
LFO_INC[v]  an LFO's phase step per frame for a 0..127 rate: 0.05 .. 20 Hz
"""
import math
from pathlib import Path

FS = 44100
OUT = Path(__file__).resolve().parents[1] / "src" / "tables.h"


def rows(vals, per):
  return "\n".join("  " + ", ".join(f"{v}u" for v in vals[i : i + per]) + "," for i in range(0, len(vals), per))


g = [round(math.tan(math.pi * (20.0 * 800.0 ** (i / 1023)) / FS) * 65536) for i in range(1024)]
ms = [max(1, round(8000.0 ** (v / 127))) for v in range(128)]
lfo = [round(0.05 * (400.0) ** (v / 127) / FS * 2**32) for v in range(128)]
OUT.write_text(
  "/* SPDX-License-Identifier: GPL-3.0-only */\n/* generated by tools/gen_tables.py: do not edit */\n"
  "#ifndef GRVBOX_TABLES_H\n#define GRVBOX_TABLES_H\n#include <stdint.h>\n\n"
  f"static const uint32_t SVF_G[1024] = {{\n{rows(g, 12)}\n}};\n\n"
  f"static const uint16_t ENV_MS[128] = {{\n{rows(ms, 16)}\n}};\n\n"
  f"static const uint32_t LFO_INC[128] = {{\n{rows(lfo, 8)}\n}};\n\n#endif\n"
)
print("wrote", OUT)
